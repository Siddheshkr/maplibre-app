-- ---------------------------------------------------------------------------
-- Parcels (polygons with an attribute used for data-driven styling)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gis.parcels (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_no text NOT NULL,
    status text NOT NULL,
    area_ha numeric(10, 3) NOT NULL,
    geom geometry(Polygon, 4326) NOT NULL
);

INSERT INTO gis.parcels (parcel_no, status, area_ha, geom)
SELECT
    'P-' || lpad(((y * 8) + x + 1)::text, 3, '0'),
    CASE
        WHEN (x + y) % 3 = 0 THEN 'vacant'
        WHEN (x + y) % 3 = 1 THEN 'allotted'
        ELSE 'reserved'
    END,
    0.420,
    ST_MakeEnvelope(
        91.47 + x * 0.026,
        23.67 + y * 0.022,
        91.47 + (x + 1) * 0.026 - 0.002,
        23.67 + (y + 1) * 0.022 - 0.002,
        4326
    )
FROM generate_series(0, 7) AS x
CROSS JOIN generate_series(0, 7) AS y
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------------------
-- Spatial indexes
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS districts_geom_idx ON gis.districts USING GIST (geom);
CREATE INDEX IF NOT EXISTS roads_geom_idx ON gis.roads USING GIST (geom);
CREATE INDEX IF NOT EXISTS facilities_geom_idx ON gis.facilities USING GIST (geom);
CREATE INDEX IF NOT EXISTS parcels_geom_idx ON gis.parcels USING GIST (geom);

-- ---------------------------------------------------------------------------
-- Read-only API user
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'gis_reader') THEN
        CREATE ROLE gis_reader LOGIN PASSWORD 'gis_reader';
    END IF;
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO gis_reader', current_database());
END
$$;

GRANT USAGE ON SCHEMA gis TO gis_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA gis TO gis_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA gis GRANT SELECT ON TABLES TO gis_reader;
