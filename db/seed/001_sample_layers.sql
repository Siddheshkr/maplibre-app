-- ---------------------------------------------------------------------------
-- Districts (polygons)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gis.districts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    state text NOT NULL,
    geom geometry(MultiPolygon, 4326) NOT NULL
);

